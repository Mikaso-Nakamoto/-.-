import re
from typing import List, Optional

def clean_telegram_markdown(text: str) -> str:
    """
    Очистка Markdown от неподдерживаемых Telegram тегов.
    Telegram не умеет рендерить заголовки ### и ## — они отображаются как мусорные решетки.
    Преобразует ### Заголовок в *Заголовок* (жирный шрифт).
    """
    if not text:
        return ""

    # Заменяем Markdown заголовки вида: "### Заголовок" -> "*Заголовок*"
    cleaned = re.sub(r'(?m)^#{1,6}\s*(.+)$', r'*\1*', text)

    # Удаляем тройные решетки посреди строк
    cleaned = re.sub(r'#{3,}', '', cleaned)

    return cleaned.strip()

