def build_digest_user_prompt(raw_items_text: str, user_interests: list, blacklist: list) -> str:
    interests_str = ", ".join([item.get("name", "") for item in user_interests if isinstance(item, dict)])
    blacklist_str = ", ".join(blacklist) if blacklist else "нет"

    return f"""Сформируй утренний дайджест на основе следующих данных:

ТЕМЫ ИНТЕРЕСА:
{interests_str}

СТОП-СЛОВА / ИСКЛЮЧЕНИЯ:
{blacklist_str}

СЫРЫЕ ПУБЛИКАЦИИ:
{raw_items_text}

Сформируй красивую, структурированную сводку для чтения в Telegram. Не придумывай факты, используй только переданную информацию.
"""
